//! Dependency resolution and the `kote.lock` file.

use crate::git;
use crate::manifest::{DepSource, GitSpec, Manifest};
use crate::registry;
use crate::semver::{Req, Version};
use std::collections::HashMap;
use std::path::{Path, PathBuf};

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PkgSource {
    Root,
    Path,
    Git { url: String, spec: GitSpec, commit: String },
    /// `registry` is the spec as written in the manifest (`None`: the default registry).
    Registry { registry: Option<String>, version: String },
}

#[derive(Clone, Debug)]
pub struct Package {
    pub name: String,
    /// The name modules of this package are linked under: `name`, or `name@series` when the
    /// graph holds several incompatible versions of it.
    pub link: String,
    pub version: String,
    pub dir: PathBuf,
    pub source: PkgSource,
    /// `(name the package uses for the dependency, index into Graph::pkgs)`
    pub deps: Vec<(String, usize)>,
}

#[derive(Clone, Debug, Default)]
pub struct Graph {
    /// `pkgs[0]` is the root package.
    pub pkgs: Vec<Package>,
}

#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// Fail instead of changing `kote.lock`.
    pub locked: bool,
    /// Never touch the network.
    pub offline: bool,
    /// Ignore the lock file for git dependencies.
    pub update: bool,
    /// Never write `kote.lock` (for editors).
    pub dry: bool,
}

/// What `kote.lock` pins: `(package name, url, query)` -> commit.
type Pins = HashMap<(String, String, Option<String>), String>;

fn read_pins(dir: &Path) -> Pins {
    let mut pins = Pins::new();
    let Ok(text) = std::fs::read_to_string(dir.join("kote.lock")) else { return pins };
    let Ok(doc) = text.parse::<toml::Table>() else { return pins };
    for p in doc.get("package").and_then(|v| v.as_array()).into_iter().flatten() {
        let (Some(name), Some(src)) = (p.get("name").and_then(|v| v.as_str()), p.get("source").and_then(|v| v.as_str())) else { continue };
        let Some(rest) = src.strip_prefix("git+") else { continue };
        let Some((loc, commit)) = rest.rsplit_once('#') else { continue };
        let (url, query) = match loc.rsplit_once('?') {
            Some((u, q)) if q.starts_with("rev=") || q.starts_with("tag=") || q.starts_with("branch=") => (u, Some(q.to_string())),
            _ => (loc, None),
        };
        pins.insert((name.to_string(), url.to_string(), query), commit.to_string());
    }
    pins
}

/// Registry versions recorded in `kote.lock`: package name -> version.
fn read_reg_pins(dir: &Path) -> HashMap<String, Vec<Version>> {
    let mut out = HashMap::new();
    let Ok(text) = std::fs::read_to_string(dir.join("kote.lock")) else { return out };
    let Ok(doc) = text.parse::<toml::Table>() else { return out };
    for p in doc.get("package").and_then(|v| v.as_array()).into_iter().flatten() {
        let is_reg = p.get("source").and_then(|v| v.as_str()).is_some_and(|s| s.starts_with("registry+"));
        let (Some(name), Some(ver)) = (p.get("name").and_then(|v| v.as_str()), p.get("version").and_then(|v| v.as_str())) else { continue };
        if let (true, Ok(v)) = (is_reg, Version::parse(ver)) {
            out.entry(name.to_string()).or_insert_with(Vec::new).push(v);
        }
    }
    out
}

pub fn render_lock(g: &Graph) -> String {
    let mut out = String::from("# This file is generated by kote. Do not edit it by hand.\nversion = 1\n");
    let mut order: Vec<&Package> = g.pkgs.iter().collect();
    order.sort_by(|a, b| (&a.name, Version::parse(&a.version).ok()).cmp(&(&b.name, Version::parse(&b.version).ok())));
    let copies = |name: &str| g.pkgs.iter().filter(|p| p.name == name).count();
    for p in order {
        out.push_str(&format!("\n[[package]]\nname = \"{}\"\nversion = \"{}\"\n", p.name, p.version));
        if let PkgSource::Git { url, spec, commit } = &p.source {
            let q = spec.query().map(|q| format!("?{q}")).unwrap_or_default();
            out.push_str(&format!("source = \"git+{url}{q}#{commit}\"\n"));
        }
        if let PkgSource::Registry { registry, .. } = &p.source {
            out.push_str(&format!("source = \"registry+{}\"\n", registry.as_deref().unwrap_or("default")));
        }
        if !p.deps.is_empty() {
            let mut names: Vec<String> = p
                .deps
                .iter()
                .map(|(_, i)| {
                    let d = &g.pkgs[*i];
                    if copies(&d.name) > 1 { format!("{} {}", d.name, d.version) } else { d.name.clone() }
                })
                .collect();
            names.sort();
            names.dedup();
            let list: Vec<String> = names.iter().map(|n| format!("\"{n}\"")).collect();
            out.push_str(&format!("dependencies = [{}]\n", list.join(", ")));
        }
    }
    out
}

struct Resolver<'a> {
    opts: Options,
    pins: &'a Pins,
    pkgs: Vec<Package>,
    /// canonical identity -> index
    seen: HashMap<String, usize>,
    stack: Vec<String>,
    /// The registry version currently assumed for each registry package.
    choices: HashMap<(String, String), Version>,
    /// Versions named by `kote.lock`, which stay usable even when yanked.
    locked: &'a HashMap<String, Vec<Version>>,
    /// Every requirement met while walking, by (name, series):
    /// (registry spec, manifest dir the spec is relative to, [(requirement, requester)]).
    reqs: HashMap<(String, String), (Option<String>, PathBuf, Vec<(Req, String)>)>,
}

impl Resolver<'_> {
    fn visit(&mut self, dir: &Path, source: PkgSource, expect_name: Option<&str>) -> Result<usize, String> {
        let manifest = Manifest::load(dir)?;
        if let Some(n) = expect_name {
            if manifest.name != n {
                return Err(format!(
                    "the dependency `{n}` points at a package named `{}` ({}); the names must match",
                    manifest.name,
                    dir.display()
                ));
            }
        }
        let id = match &source {
            PkgSource::Git { url, commit, .. } => format!("git:{url}#{commit}"),
            PkgSource::Registry { .. } => format!("reg:{}", dir.display()),
            _ => format!("path:{}", dir.display()),
        };
        if let Some(&i) = self.seen.get(&id) {
            if self.stack.contains(&id) {
                let mut chain: Vec<String> = self.stack.iter().skip_while(|s| **s != id).map(|s| s.rsplit('/').next().unwrap_or(s).to_string()).collect();
                chain.push(manifest.name.clone());
                return Err(format!("dependency cycle: {}", chain.join(" -> ")));
            }
            return Ok(i);
        }
        let is_reg = matches!(source, PkgSource::Registry { .. });
        let clash = self.pkgs.iter().enumerate().find(|(_, p)| p.name == manifest.name && !(is_reg && matches!(p.source, PkgSource::Registry { .. })));
        if let Some((other, _)) = clash.map(|(i, p)| (p.dir.display().to_string(), i)) {
            return Err(format!(
                "two different packages are both named `{}`: {} and {}",
                manifest.name,
                other,
                dir.display()
            ));
        }
        let idx = self.pkgs.len();
        self.pkgs.push(Package { name: manifest.name.clone(), link: manifest.name.clone(), version: manifest.version.clone(), dir: dir.to_path_buf(), source, deps: vec![] });
        self.seen.insert(id.clone(), idx);
        self.stack.push(id);
        let mut deps = vec![];
        for d in &manifest.deps {
            let i = match &d.source {
                DepSource::Path(p) => {
                    let target = dir.join(p);
                    let target = target
                        .canonicalize()
                        .map_err(|_| format!("dependency `{}`: cannot find {} (from {})", d.name, target.display(), dir.join("kote.toml").display()))?;
                    self.visit(&target, PkgSource::Path, Some(&d.name))?
                }
                DepSource::Registry { req, registry: spec } => {
                    let reg = registry::open(spec.as_deref(), dir);
                    reg.sync(&d.name, self.opts.offline).map_err(|e| format!("dependency `{}`: {e}", d.name))?;
                    let parsed = Req::parse(req).map_err(|e| format!("dependency `{}`: {e}", d.name))?;
                    let keep = self.locked.get(&d.name).cloned().unwrap_or_default();
                    let avail = reg.versions(&d.name, &keep);
                    if avail.is_empty() && reg.has_versions(&d.name) {
                        return Err(format!("dependency `{}`: every published version of `{}` is yanked", d.name, d.name));
                    }
                    if avail.is_empty() {
                        return Err(format!(
                            "dependency `{}`: no package named `{}` in the registry at {}\nhelp: publish it with `kote publish`, or set `KOTE_REGISTRY` / `registry = \"DIR\"`",
                            d.name,
                            d.name,
                            reg.describe()
                        ));
                    }
                    // Prefer a version already chosen for this package that satisfies the requirement.
                    let chosen = self.choices.iter().filter(|((n, _), v)| *n == d.name && parsed.matches(v) && avail.contains(v)).map(|(_, v)| *v).max();
                    let version = match chosen {
                        Some(v) => v,
                        None => *avail.iter().rev().find(|v| parsed.matches(v)).ok_or_else(|| no_match(&d.name, &[(parsed.clone(), manifest.name.clone())], &avail))?,
                    };
                    let key = (d.name.clone(), version.series());
                    self.choices.entry(key.clone()).or_insert(version);
                    self.reqs.entry(key).or_insert_with(|| (spec.clone(), dir.to_path_buf(), vec![])).2.push((parsed.clone(), manifest.name.clone()));
                    let target = reg.package_dir(&d.name, &version);
                    self.visit(&target, PkgSource::Registry { registry: spec.clone(), version: version.to_string() }, Some(&d.name))?
                }
                DepSource::Git { url, spec } => {
                    let pinned = if self.opts.update {
                        None
                    } else {
                        self.pins.get(&(d.name.clone(), url.clone(), spec.query())).cloned()
                    };
                    let (checkout, commit) = git::fetch(&d.name, url, spec, pinned.as_deref(), self.opts.offline)
                        .map_err(|e| format!("dependency `{}`: {e}", d.name))?;
                    self.visit(&checkout, PkgSource::Git { url: url.clone(), spec: spec.clone(), commit }, Some(&d.name))?
                }
            };
            deps.push((d.name.clone(), i));
        }
        self.stack.pop();
        self.pkgs[idx].deps = deps;
        Ok(idx)
    }
}

fn no_match(name: &str, reqs: &[(Req, String)], avail: &[Version]) -> String {
    let list: Vec<String> = avail.iter().map(Version::to_string).collect();
    let mut m = if reqs.len() == 1 {
        format!("dependency `{name}`: no published version matches `{}`", reqs[0].0)
    } else {
        format!("no version of `{name}` satisfies every requirement")
    };
    for (r, who) in reqs {
        m.push_str(&format!("\n  `{who}` requires {name} {r}"));
    }
    m.push_str(&format!("\navailable versions: {}", list.join(", ")));
    m
}

/// Resolve the dependency graph of the package in `dir`, reading and (unless
/// `locked`) updating `kote.lock`.
///
/// Registry packages get one version per compatibility series (`1.x`, `2.x`, `0.3.x`...):
/// the highest that satisfies every requirement on that series (or the locked one, when it
/// still does). Two requirements that fall in different series, such as `^1.2` and `^2.0`,
/// give two copies of the package, linked as `name@1` and `name@2`. Yanked versions are
/// skipped unless the lock file names them. Choosing a version can change which
/// requirements exist, so the walk repeats until it is stable.
pub fn resolve(dir: &Path, opts: Options) -> Result<Graph, String> {
    let dir = dir.canonicalize().map_err(|e| format!("cannot open {}: {e}", dir.display()))?;
    let pins = read_pins(&dir);
    let locked_versions = if opts.update { HashMap::new() } else { read_reg_pins(&dir) };
    let mut choices: HashMap<(String, String), Version> = HashMap::new();
    for (name, vs) in &locked_versions {
        for v in vs {
            choices.insert((name.clone(), v.series()), *v);
        }
    }
    let mut graph = None;
    for _ in 0..32 {
        let mut r = Resolver { opts, pins: &pins, pkgs: vec![], seen: HashMap::new(), stack: vec![], choices: choices.clone(), locked: &locked_versions, reqs: HashMap::new() };
        r.visit(&dir, PkgSource::Root, None)?;
        let mut next: HashMap<(String, String), Version> = HashMap::new();
        for (key, (spec, base, reqs)) in &r.reqs {
            let reg = registry::open(spec.as_deref(), base);
            let keep = locked_versions.get(&key.0).cloned().unwrap_or_default();
            let avail: Vec<Version> = reg.versions(&key.0, &keep).into_iter().filter(|v| v.series() == key.1).collect();
            let ok = |v: &Version| reqs.iter().all(|(q, _)| q.matches(v));
            let pick = keep.iter().find(|v| v.series() == key.1 && avail.contains(v) && ok(v)).copied().or_else(|| avail.iter().rev().find(|v| ok(v)).copied());
            match pick {
                Some(v) => {
                    next.insert(key.clone(), v);
                }
                None => return Err(no_match(&key.0, reqs, &avail)),
            }
        }
        let stable = next.iter().all(|(n, v)| choices.get(n) == Some(v)) && r.reqs.len() == next.len();
        if stable {
            graph = Some(Graph { pkgs: r.pkgs });
            break;
        }
        choices = next;
    }
    let graph = graph.ok_or("could not find a stable set of package versions (the requirements keep changing each other)")?;
    let mut graph = graph;
    let mut count: HashMap<String, usize> = HashMap::new();
    for p in &graph.pkgs {
        if matches!(p.source, PkgSource::Registry { .. }) {
            *count.entry(p.name.clone()).or_insert(0) += 1;
        }
    }
    for p in &mut graph.pkgs {
        if count.get(&p.name).is_some_and(|&n| n > 1) {
            if let Ok(v) = Version::parse(&p.version) {
                p.link = format!("{}@{}", p.name, v.series());
            }
        }
    }
    let lock = render_lock(&graph);
    let path = dir.join("kote.lock");
    let current = std::fs::read_to_string(&path).ok();
    if current.as_deref() != Some(lock.as_str()) && !opts.dry {
        if opts.locked {
            return Err("kote.lock needs to be updated, but --locked was given".into());
        }
        std::fs::write(&path, lock).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    Ok(graph)
}
